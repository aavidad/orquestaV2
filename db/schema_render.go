func joinDDLParts(parts ...string) string {
	var out []string
	for _, part := range parts {
		part = strings.TrimSpace(part)
		if part == "" {
			continue
		}
		out = append(out, part)
	}
	return strings.Join(out, "\n\n")
}

func schemaStatements(schema string) []string {
	schema = strings.TrimSpace(schema)
	if schema == "" {
		return nil
	}
	var (
		statements []string
		current    strings.Builder
		inSingle   bool
		inDouble   bool
	)
	flush := func() {
		stmt := strings.TrimSpace(current.String())
		if stmt != "" {
			statements = append(statements, stmt)
		}
		current.Reset()
	}
	for i := 0; i < len(schema); i++ {
		ch := schema[i]
		switch ch {
		case '\'':
			if !inDouble {
				if inSingle && i+1 < len(schema) && schema[i+1] == '\'' {
					current.WriteByte(ch)
					current.WriteByte(schema[i+1])
					i++
					continue
				}
				inSingle = !inSingle
			}
		case '"':
			if !inSingle {
				inDouble = !inDouble
			}
		case ';':
			current.WriteByte(ch)
			if !inSingle && !inDouble {
				flush()
				continue
			}
		}
		current.WriteByte(ch)
	}
	flush()
	return statements
}

func aplicarDDL(db *sql.DB, ddl string) error {
	ddl = strings.TrimSpace(ddl)
	if ddl == "" {
		return fmt.Errorf("schema DDL vacio")
	}
	_, err := db.Exec(ddl)
	return err
}

func aplicarSeedSQL(db *sql.DB, seeds string) error {
	seeds = strings.TrimSpace(seeds)
	if seeds == "" {
		return nil
	}
	_, err := db.Exec(seeds)
	return err
}
