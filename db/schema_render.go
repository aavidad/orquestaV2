func renderIndexDDL() string {
	return strings.Join(indexStatements(), "\n\n")
}

func renderSQLiteUpdatedAtDDL() string {
	var b strings.Builder
	for _, table := range updatedAtTables() {
		b.WriteString("CREATE TRIGGER IF NOT EXISTS trig_")
		b.WriteString(table)
		b.WriteString("_updated\n")
		b.WriteString("    AFTER UPDATE ON ")
		b.WriteString(table)
		b.WriteString("\n")
		b.WriteString("BEGIN\n")
		b.WriteString("    UPDATE ")
		b.WriteString(table)
		b.WriteString(" SET updated_at = CURRENT_TIMESTAMP WHERE id = NEW.id;\n")
		b.WriteString("END;\n\n")
	}
	return strings.TrimSpace(b.String())
}

