package db

import "strings"

func schemaDDL() string {
	return schemaDDLForDriver(DriverName())
}

func schemaDDLForDriver(driver string) string {
	switch strings.TrimSpace(strings.ToLower(driver)) {
	case "postgres":
		return renderPostgresSchemaDDL(Schema)
	default:
		return strings.TrimSpace(Schema)
	}
}

func renderPostgresSchemaDDL(schema string) string {
	lines := strings.Split(schema, "\n")
	out := make([]string, 0, len(lines))
	skipTrigger := false
	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, "CREATE TRIGGER IF NOT EXISTS ") {
			skipTrigger = true
			continue
		}
		if skipTrigger {
			if trimmed == "END;" {
				skipTrigger = false
			}
			continue
		}
		line = strings.ReplaceAll(line, "INTEGER PRIMARY KEY AUTOINCREMENT", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
		line = strings.ReplaceAll(line, " DATETIME", " TIMESTAMP")
		out = append(out, line)
	}
	return strings.TrimSpace(strings.Join(out, "\n"))
}
